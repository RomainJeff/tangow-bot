import { type ColorTokens, darkTokens, lightTokens, radii } from "@tangow/ui-tokens";

export const SHARE_TOKENS_SWIFT_PATH = "targets/share/ShareTokens.swift";

/** The token slots the share extension draws with. */
const SLOTS = [
  "background",
  "group",
  "foreground",
  "mutedForeground",
  "foregroundSubtle",
  "border",
  "well",
  "accent",
  "destructive",
] as const satisfies readonly (keyof ColorTokens)[];

function hex(value: string): string {
  if (!/^#[0-9a-f]{6}$/i.test(value))
    throw new Error(`Share tokens need opaque hex colors: ${value}`);
  return `0x${value.slice(1).toUpperCase()}`;
}

/** Swift source for the share extension's colors and radii, generated from `@tangow/ui-tokens`. */
export function shareTokensSwift(): string {
  const colors = SLOTS.map(
    (slot) =>
      `  static let ${slot} = Color(light: ${hex(lightTokens[slot])}, dark: ${hex(darkTokens[slot])})`,
  );
  return [
    "// Generated by `pnpm --filter @tangow/mobile generate:share-tokens` from @tangow/ui-tokens. Do not edit.",
    "import SwiftUI",
    "",
    "enum Tokens {",
    ...colors,
    `  static let groupRadius: CGFloat = ${radii.mobileGroup}`,
    `  static let cardRadius: CGFloat = ${radii.card}`,
    "}",
    "",
  ].join("\n");
}
