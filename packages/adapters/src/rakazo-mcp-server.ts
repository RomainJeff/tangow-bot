import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { CallToolRequestSchema, ListToolsRequestSchema } from "@modelcontextprotocol/sdk/types.js";
import type { AgentRunRequest } from "@rakazo/adapter-kit";
import { z } from "zod";
import type { NativeSessionHost } from "./native-session-host.js";
import type { McpBridgeDeps, McpCallResult } from "./rakazo-mcp-bridge.js";
import { callAuthorizedTool } from "./rakazo-mcp-bridge.js";

/**
 * T02 S3 "point d'entrée MCP authentifié" : the server surface a native
 * process actually connects to. The ticket is bound to this server instance
 * at construction time (never a tool argument the model can see or supply,
 * S3/finding 3); `callId` is generated by the server on every call, so a
 * client can neither provide nor preempt one. The server never trusts an
 * identity carried in the tool's own business arguments, and only ever
 * exposes the tools present in `deps.catalog` (closed catalog): anything
 * else is a protocol-level "tool not found" from the SDK itself, before this
 * module's own authorization (ticket/generation/replay) even runs.
 *
 * B1 (statu quo, T02:5 review): a retransmission of the same JSON-RPC id
 * collapses to a single effect, but the second attempt receives the tool
 * error `duplicate_call`, never the memoized result of the first. Replaying
 * the actual result would require persisting call results (a schema change)
 * and is out of scope for T02; tracked as backlog for the composed-admission
 * loop (E2), where a real client's retry-on-timeout behavior against this
 * error can be observed.
 */
export interface RakazoMcpServerOptions {
  name?: string;
  version?: string;
  /** Ticket bound to this server instance/process; never exposed to the model. */
  ticket: string;
  /** The armed run is part of replay identity, not a model-controlled argument. */
  runId?: string;
  /** Real run catalogue supplied by the executor composition seam. */
  tools?: ReadonlyArray<RakazoMcpTool>;
}

export type RakazoMcpTool = {
  name: string;
  description: string;
  inputSchema: Record<string, unknown>;
  route?: {
    connectorId: string;
    toolName: string;
    resourceId?: string;
    resourceRevision?: string | number;
  };
};

const CALL_ENVELOPE_SHAPE = {
  args: z.record(z.string(), z.unknown()).default({}),
};

export function createRakazoMcpServer(
  deps: McpBridgeDeps,
  options: RakazoMcpServerOptions,
): McpServer {
  const server = new McpServer(
    { name: options.name ?? "rakazo-native", version: options.version ?? "0.0.0" },
    { capabilities: { tools: {} } },
  );

  // The SDK's high-level registration takes Zod schemas.  Run tools already
  // have JSON Schema, so use the documented low-level request handlers to
  // return that exact schema instead of wrapping every tool in `{ args }`.
  if (options.tools) {
    const byName = new Map(options.tools.map((tool) => [tool.name, tool]));
    server.server.setRequestHandler(ListToolsRequestSchema, async () => ({
      tools: options.tools!.map(({ name, description, inputSchema }) => ({
        name,
        description,
        inputSchema,
      })),
    }));
    server.server.setRequestHandler(CallToolRequestSchema, async (request, extra) => {
      const tool = byName.get(request.params.name);
      if (!tool) return toCallToolResult({ ok: false, error: "tool_not_allowed" });
      const outcome = await callAuthorizedTool(deps, {
        ticket: options.ticket,
        callId: deriveCallId(
          options.ticket,
          options.runId ?? "",
          extra.sessionId ?? "",
          extra.requestId,
        ),
        toolName: tool.name,
        args: (request.params.arguments ?? {}) as Record<string, unknown>,
      });
      return toCallToolResult(outcome);
    });
    return server;
  }

  for (const toolName of deps.catalog) {
    server.registerTool(
      toolName,
      {
        description: `Rakazo-authorized native tool "${toolName}"`,
        inputSchema: CALL_ENVELOPE_SHAPE,
      },
      async ({ args }, extra) => {
        const outcome = await callAuthorizedTool(deps, {
          ticket: options.ticket,
          callId: deriveCallId(
            options.ticket,
            options.runId ?? "",
            extra.sessionId ?? "",
            extra.requestId,
          ),
          toolName,
          args,
        });
        return toCallToolResult(outcome);
      },
    );
  }

  return server;
}

/**
 * Deterministic `callId`, scoped by ticket and the transport's own JSON-RPC
 * request id (`extra.requestId`, SDK 1.30.0 `RequestHandlerExtra`): a
 * retransmission of the same `tools/call` carries the same JSON-RPC id, so it
 * derives the same `callId` and `reserveCall` collapses it to one operation
 * (`duplicate_call`); two distinct requests always carry distinct ids, hence
 * distinct callIds. The JSON-RPC id's type is encoded alongside its value
 * (`typeof requestId`) so `id: 1` and `id: "1"` — two distinct requests —
 * never collapse onto the same `callId`. Never derived from, or accepted
 * from, the client's own tool arguments.
 */
export function deriveCallId(
  ticket: string,
  runId: string,
  sessionId: string,
  requestId: string | number,
): string {
  return createHash("sha256")
    .update(JSON.stringify([ticket, runId, sessionId, typeof requestId, requestId]))
    .digest("hex")
    .slice(0, 32);
}

function toCallToolResult(outcome: McpCallResult) {
  if (outcome.ok) {
    return {
      content: [{ type: "text" as const, text: JSON.stringify(outcome.result) }],
    };
  }
  return {
    isError: true,
    content: [{ type: "text" as const, text: outcome.error }],
  };
}

/**
 * Handle T01's native runtime composes to flip `tools: false` to a real MCP
 * endpoint for an attempt: a real, produced factory result (S3/finding 7 —
 * replaces the speculative `NativeToolServerHandle`). `endpoint` is the
 * subset T01 declares independently (`command`/`args`/`env`/`ticket`/
 * `close`); no in-process `Transport` variant, since the endpoint's process
 * runs in the Computer's container while this factory and the session host
 * run in the worker (frontier out of scope for this loop — see the
 * receipt's "besoin transmis au coordinateur").
 */
export interface NativeToolServer {
  endpoint:
    | { command: string; args: string[]; env?: Record<string, string> }
    | { url: string; httpHeaders: Record<string, string> };
  /** Ticket is private runtime configuration, never a model tool argument. */
  ticket: string;
  /** Arms this process ticket for one native turn immediately before turn/start. */
  arm?(attempt: AgentRunRequest): Promise<void>;
  /** Parks this process ticket after turn completion, before the process is retained. */
  disarm?(): Promise<void>;
  close(): Promise<void>;
}

export interface CreateNativeToolServerOptions {
  botId: string;
  threadId: string;
  /** Executable to run the stdio entry point with; defaults to this Node process's own binary. */
  command?: string;
  /** Overrides the resolved path to `rakazo-mcp-stdio.js`; test seam only. */
  stdioEntryPointPath?: string;
}

/**
 * Issues a ticket for this bot/thread binding and describes the stdio
 * process a native runtime should spawn to reach it: `endpoint.env` carries
 * `RAKAZO_MCP_TICKET`, never a tool argument. `close()` revokes only this
 * ticket (atomic no-op if it was already superseded), leaving the generation
 * untouched: routine cleanup of an attempt that ended normally must not
 * invalidate a newer attempt's ticket the way `advanceGeneration` would.
 */
export async function createNativeToolServer(
  host: NativeSessionHost,
  options: CreateNativeToolServerOptions,
): Promise<NativeToolServer> {
  await host.ensureBinding(options.botId, options.threadId);
  const { ticket } = await host.issueTicket(options.botId, options.threadId);
  const entryPoint =
    options.stdioEntryPointPath ?? fileURLToPath(new URL("./rakazo-mcp-stdio.js", import.meta.url));

  return {
    endpoint: {
      command: options.command ?? process.execPath,
      args: [entryPoint],
      env: { RAKAZO_MCP_TICKET: ticket },
    },
    ticket,
    async close() {
      await host.revokeTicket(options.botId, options.threadId, ticket);
    },
  };
}
