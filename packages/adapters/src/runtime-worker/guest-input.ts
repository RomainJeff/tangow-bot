import type {
  AgentRunModel,
  AgentRunRequest,
  ConnectorTool,
  GuestRunInput,
  GuestTool,
  HarnessCapability,
  HarnessDeclaration,
  WorkerStartV1,
} from "@rakazo/adapter-kit";
import type { HelperProfile } from "@rakazo/core";
import { selectTools } from "@rakazo/core";
import { isHelperTool } from "../builtin-tools.js";
import { catalogIndexText, isLazyCatalogControlRoute } from "../lazy-tool-catalog.js";
import { encodeMessage } from "./framing.js";
import { WORKER_LIMITS } from "./limits.js";
import { guestModelOf } from "./model-relay.js";
import piTools from "./pi-tools.json" with { type: "json" };

/** SDK-free manifest generated by the Pi adapter. No harness SDK loads in the controller. */
export const WORKER_NATIVE_TOOLS: readonly ConnectorTool[] = piTools;

export function nativeToolsForHarness(name: string): readonly ConnectorTool[] {
  if (name === "pi-native")
    return [
      ...WORKER_NATIVE_TOOLS,
      {
        name: "tool_search",
        description: "Discover deferred tools",
        readOnly: true,
        inputSchema: {
          type: "object",
          properties: { query: { type: "string" }, limit: { type: "number" } },
          required: ["query"],
        },
      },
    ];
  return [];
}

/** The tools a harness uses only through a capability it declares. */
const TOOL_CAPABILITY: Readonly<Record<string, HarnessCapability>> = { run_subagent: "subagents" };

type ToolRule = Pick<HelperProfile, "allow" | "block">;

const mainBotRule = (request: AgentRunRequest): ToolRule => ({
  allow: ["*"],
  block: request.blockedTools,
});

/** The tools one agent is offered: those its harness can use, selected by `rule`. */
function agentTools(tools: readonly ConnectorTool[], harness: HarnessDeclaration, rule: ToolRule) {
  const nativeNames = new Set(nativeToolsForHarness(harness.name).map((tool) => tool.name));
  return selectTools(
    tools
      .filter((tool) => {
        const needed = TOOL_CAPABILITY[tool.name];
        return !needed || harness.capabilities.includes(needed);
      })
      .map((tool) => ({
        ...tool,
        where: nativeNames.has(tool.name) ? ("guest" as const) : ("controller" as const),
      })),
    rule,
  );
}

const availableHelpers = (profiles: readonly HelperProfile[]) =>
  [
    "<available_helpers>",
    ...profiles.map(({ name, description }) => `- ${name}: ${description}`),
    "</available_helpers>",
  ].join("\n");

const withHelperChoice = (
  schema: ConnectorTool["inputSchema"],
  profiles: readonly HelperProfile[],
): ConnectorTool["inputSchema"] => ({
  ...schema,
  properties: {
    ...(schema.properties as Record<string, unknown>),
    helper: {
      type: "string",
      enum: profiles.map((profile) => profile.name),
      description: "Optional helper from <available_helpers> to run the task.",
    },
  },
});

/** What marking one search, load or execute tool as a catalog's fallback adds to the frame. */
const FALLBACK_MARK_BYTES = Buffer.byteLength(',"catalog":"fallback"');

/**
 * Each lazy catalog's tools, for a harness with native tool search, and what sending them costs:
 * the entries and the fallback marks on the catalog's search, load and execute tools.
 */
function lazyCatalogs(offered: readonly ConnectorTool[]) {
  const taken = new Set(offered.map((tool) => tool.name));
  return offered.flatMap((tool) => {
    const connectorId = tool.route?.connectorId;
    if (!tool.catalog?.length || !connectorId) return [];
    const entries: GuestTool[] = tool.catalog
      .filter((entry) => !taken.has(entry.tool.name))
      .map(({ id, tool: { name, description, inputSchema, readOnly } }) => ({
        name,
        description,
        inputSchema,
        ...(readOnly === undefined ? {} : { readOnly }),
        where: "controller",
        catalog: { via: tool.name, id },
      }));
    for (const entry of entries) taken.add(entry.name);
    const controls = offered.filter(
      ({ route }) => route?.connectorId === connectorId && isLazyCatalogControlRoute(route),
    ).length;
    const bytes = Buffer.byteLength(JSON.stringify(entries)) + controls * FALLBACK_MARK_BYTES;
    return [{ connectorId, entries, bytes }];
  });
}

export function base64Images(images: AgentRunRequest["currentTurnImages"]) {
  return (images ?? []).map((image) => ({
    name: image.name,
    mimeType: image.mimeType,
    data: Buffer.from(image.data).toString("base64"),
  }));
}

/**
 * The start message for a harness. Catalogs go in while the whole encoded message fits the
 * controller's frame cap; one that does not stays behind its search, load and execute tools.
 */
export function workerStart(
  envelope: Omit<WorkerStartV1, "run">,
  request: AgentRunRequest,
  harness: HarnessDeclaration,
): WorkerStartV1 {
  const offered = agentTools(request.tools, harness, mainBotRule(request));
  const profiles = request.helperProfiles ?? [];
  // A harness with its own loop keeps its own prompt: Rakazo's part is appended to it.
  const instructions = harness.capabilities.includes("native-loop")
    ? (request.harnessAddendum ?? request.instructions)
    : request.instructions;
  const input: GuestRunInput = {
    botId: request.botId,
    threadId: request.threadId,
    sourceMessageId: request.sourceMessageId,
    prompt: request.prompt,
    instructions: profiles.length
      ? `${instructions}\n\n${availableHelpers(profiles)}`
      : instructions,
    history: request.history.map((turn) => ({
      ...(turn.id ? { id: turn.id } : {}),
      role: turn.role,
      content: turn.content,
      ...(turn.parts ? { parts: turn.parts } : {}),
    })),
    images: base64Images(request.currentTurnImages),
    tools: offered.map(({ name, description, inputSchema, readOnly, where }) => ({
      name,
      description,
      inputSchema:
        name === "run_subagent" && profiles.length
          ? withHelperChoice(inputSchema, profiles)
          : inputSchema,
      ...(readOnly === undefined ? {} : { readOnly }),
      where,
    })),
    model: guestModelOf(request.model),
    allowSilentEmpty: request.allowSilentEmpty,
    freeTextIsPrivate: request.freeTextIsPrivate,
    runRecap: request.runRecap,
    emptyResponseText: request.emptyResponseText,
  };
  const start = (sent: ReturnType<typeof lazyCatalogs>): WorkerStartV1 => {
    const fallback = new Set(sent.map((catalog) => catalog.connectorId));
    return {
      ...envelope,
      run: {
        ...input,
        tools: [
          ...input.tools.map((tool, index) => {
            const route = offered[index]!.route;
            return route && isLazyCatalogControlRoute(route) && fallback.has(route.connectorId)
              ? { ...tool, catalog: "fallback" as const }
              : tool;
          }),
          ...sent.flatMap((catalog) => catalog.entries),
        ],
      },
    };
  };
  const bytes = (message: WorkerStartV1) => encodeMessage(message).byteLength;
  let room = WORKER_LIMITS.controllerFrameBytes - bytes(start([]));
  const sent = lazyCatalogs(offered).filter((catalog) => {
    if (catalog.bytes > room) return false;
    room -= catalog.bytes;
    return true;
  });
  let message = start(sent);
  while (sent.length > 0 && bytes(message) > WORKER_LIMITS.controllerFrameBytes) {
    sent.pop();
    message = start(sent);
  }
  return message;
}

export function helperRunInput(
  envelope: Omit<WorkerStartV1, "run">,
  request: AgentRunRequest,
  harness: HarnessDeclaration,
  helper: { task: string; instructions: string; model: AgentRunModel; profile?: HelperProfile },
): GuestRunInput {
  const tools = agentTools(request.tools, harness, helper.profile ?? mainBotRule(request)).filter(
    (tool) => isHelperTool(tool.name),
  );
  const parent = workerStart(
    envelope,
    {
      ...request,
      history: [],
      currentTurnImages: [],
      tools,
      // The helper's tools are selected already: the parent's block list must not apply again.
      blockedTools: [],
      helperProfiles: [],
    },
    harness,
  ).run;
  return {
    botId: parent.botId,
    threadId: parent.threadId,
    sourceMessageId: parent.sourceMessageId,
    prompt: helper.task,
    instructions: [helper.instructions, catalogIndexText(tools)].filter(Boolean).join("\n\n"),
    history: [],
    images: [],
    tools: parent.tools.filter((tool) => isHelperTool(tool.name)),
    model: guestModelOf(helper.model),
  };
}
